@dataclass(frozen=True, slots=True)
class S2:
    """Total spin-squared operator.

    ``local_conn`` returns the diagonal S_z^2 + (N_single / 2) term plus
    spin-exchange bras generated by S_- S_+ and S_+ S_-.
    """

    sector: Any

    def diag(self, ket: Any) -> NDArray[np.float64]:
        ket = np.asarray(ket, dtype=np.uint64)

        if isinstance(self.sector, DetSector):
            n_alpha = _count(ket[:, 0])
            n_beta = _count(ket[:, 1])
            n_double = _count(ket[:, 0] & ket[:, 1])
            n_single = n_alpha + n_beta - 2 * n_double
            m = 0.5 * (n_alpha - n_beta)
            return m * m + 0.5 * n_single.astype(np.float64)

        raise TypeError(f"unsupported sector: {type(self.sector).__name__}")

    def local_conn(
        self,
        ket: Any,
    ) -> tuple[
        NDArray[np.float64],
        NDArray[np.int64],
        NDArray[np.uint64],
        NDArray[np.float64],
    ]:
        """Return diagonal, CSR pointer, spin-exchange bras, and values."""
        ket = np.ascontiguousarray(ket, dtype=np.uint64)
        diag = self.diag(ket)
        n_ket = int(ket.shape[0])

        if not isinstance(self.sector, DetSector):
            raise TypeError(f"unsupported sector: {type(self.sector).__name__}")

        norb = int(self.sector.norb)
        orb = np.arange(norb, dtype=np.int64)
        word = orb >> 6
        bit = np.left_shift(np.uint64(1), (orb & 63).astype(np.uint64))

        alpha = (ket[:, 0, word] & bit) != 0
        beta = (ket[:, 1, word] & bit) != 0
        aonly = alpha & ~beta
        bonly = beta & ~alpha
        single = alpha ^ beta

        count = aonly.sum(axis=1, dtype=np.int64) * bonly.sum(axis=1, dtype=np.int64)
        ptr = np.empty(n_ket + 1, dtype=np.int64)
        ptr[0] = 0
        np.cumsum(count, out=ptr[1:])

        bra = np.empty((int(ptr[-1]),) + ket.shape[1:], dtype=np.uint64)
        val = np.empty(int(ptr[-1]), dtype=np.float64)

        # Prefix parity over singly occupied orbitals gives the exchange sign.
        prefix = np.empty((n_ket, norb + 1), dtype=np.int64)
        prefix[:, 0] = 0
        np.cumsum(single, axis=1, dtype=np.int64, out=prefix[:, 1:])

        for iket in range(n_ket):
            lo = int(ptr[iket])
            hi = int(ptr[iket + 1])
            if lo == hi:
                continue

            pa = np.flatnonzero(aonly[iket])
            qb = np.flatnonzero(bonly[iket])
            p = np.repeat(pa, qb.size)
            q = np.tile(qb, pa.size)
            item = np.arange(p.size)

            y = np.repeat(ket[iket : iket + 1], p.size, axis=0)
            wp, bp = word[p], bit[p]
            wq, bq = word[q], bit[q]

            y[item, 0, wp] &= ~bp
            y[item, 1, wp] |= bp
            y[item, 1, wq] &= ~bq
            y[item, 0, wq] |= bq

            left = np.minimum(p, q)
            right = np.maximum(p, q)
            parity = (prefix[iket, right] - prefix[iket, left + 1]) & 1

            bra[lo:hi] = y
            val[lo:hi] = 2.0 * parity.astype(np.float64) - 1.0

        return diag, ptr, bra, val

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import numpy as np
from numpy.typing import NDArray

from ..hilbert import DetSector


def _count(words: NDArray[Any]) -> NDArray[np.int64]:
    """Count occupied spin orbitals in packed words."""
    return np.bitwise_count(words).sum(axis=-1, dtype=np.int64)


def occupation(ket: Any, spin: int, p: int) -> NDArray[np.float64]:
    """Return n_{spin,p}(ket)."""
    ket = np.asarray(ket, dtype=np.uint64)
    spin = int(spin)
    p = int(p)
    word = p >> 6
    bit = np.uint64(1) << np.uint64(p & 63)
    return ((ket[:, spin, word] & bit) != 0).astype(np.float64)


def _parity(ket: NDArray[np.uint64], spin: int, p: int) -> NDArray[np.int64]:
    """Return the Jordan-Wigner count before spin orbital (spin, p)."""
    word = p >> 6
    before = np.zeros(ket.shape[0], dtype=np.int64)
    if spin == 1:
        before += _count(ket[:, 0, :])
    if word:
        before += _count(ket[:, spin, :word])
    mask = (
        (np.uint64(1) << np.uint64(p & 63)) - np.uint64(1)
        if p & 63
        else np.uint64(0)
    )
    if mask:
        before += np.bitwise_count(ket[:, spin, word] & mask).astype(np.int64)
    return before


def annihilate(
    ket: Any,
    spin: int,
    p: int,
) -> tuple[NDArray[np.uint64], NDArray[np.float64], NDArray[np.bool_]]:
    """Apply c_{spin,p} to each ket."""
    ket = np.ascontiguousarray(ket, dtype=np.uint64)
    spin = int(spin)
    p = int(p)
    word = p >> 6
    bit = np.uint64(1) << np.uint64(p & 63)

    active = (ket[:, spin, word] & bit) != 0
    bra = np.ascontiguousarray(ket.copy())
    bra[active, spin, word] &= ~bit
    sign = np.where(_parity(ket, spin, p) & 1, -1.0, 1.0)
    return bra, sign.astype(np.float64), active


def create(
    ket: Any,
    spin: int,
    p: int,
) -> tuple[NDArray[np.uint64], NDArray[np.float64], NDArray[np.bool_]]:
    """Apply c^dagger_{spin,p} to each ket."""
    ket = np.ascontiguousarray(ket, dtype=np.uint64)
    spin = int(spin)
    p = int(p)
    word = p >> 6
    bit = np.uint64(1) << np.uint64(p & 63)

    active = (ket[:, spin, word] & bit) == 0
    bra = np.ascontiguousarray(ket.copy())
    bra[active, spin, word] |= bit
    sign = np.where(_parity(ket, spin, p) & 1, -1.0, 1.0)
    return bra, sign.astype(np.float64), active


def number(
    ket: Any,
    spin: int | None = None,
    p: int | None = None,
) -> NDArray[np.float64]:
    """Return particle number on an orbital, spin block, or full ket."""
    ket = np.asarray(ket, dtype=np.uint64)
    if p is not None:
        if spin is None:
            return occupation(ket, 0, int(p)) + occupation(ket, 1, int(p))
        return occupation(ket, int(spin), int(p))
    if spin is not None:
        return _count(ket[:, int(spin), :]).astype(np.float64)
    return (
        _count(ket[:, 0, :]).astype(np.float64)
        + _count(ket[:, 1, :]).astype(np.float64)
    )


def sz(ket: Any) -> NDArray[np.float64]:
    """Return S_z(ket) = (N_alpha - N_beta) / 2."""
    ket = np.asarray(ket, dtype=np.uint64)
    return 0.5 * (
        _count(ket[:, 0, :]).astype(np.float64)
        - _count(ket[:, 1, :]).astype(np.float64)
    )


@dataclass(frozen=True, slots=True)
class Number:
    """Particle-number operator."""

    sector: Any

    def diag(self, ket: Any) -> NDArray[np.float64]:
        return number(ket)

    def local_conn(
        self,
        ket: Any,
    ) -> tuple[
        NDArray[np.float64],
        NDArray[np.int64],
        NDArray[np.uint64],
        NDArray[np.float64],
    ]:
        ket = np.ascontiguousarray(ket, dtype=np.uint64)
        return (
            self.diag(ket),
            np.zeros(ket.shape[0] + 1, dtype=np.int64),
            ket[:0].copy(),
            np.empty(0, dtype=np.float64),
        )


